-- Example 06 — Presence + Typed Broadcast
--
-- The realtime-channel side of pg_reactive — orthogonal to live queries.
-- A channel is just a name (still a query_id, but you don't have to
-- register one — clients can subscribe to anything matching the regex).
-- It carries two kinds of frames:
--
--   * presence   client → channel: "here's my state"; channel keeps a
--                map per client_id and pushes presence_state /
--                presence_join / presence_leave events.
--   * broadcast  client → channel: peer-to-peer message. The proxy wraps
--                it as {type:"broadcast", from:<peer-id>, payload:<orig>}
--                so receivers cannot confuse a peer with a server delta.
--
-- Since 2026-05, the server rejects ANYTHING else from the client side
-- (no raw {inserted:[...]} forgery possible).
--
-- For private channels, register one server-side with audience binding.
-- For public chat rooms / open lobbies, just use a public channel name.

-- No tables, no subscriptions: pgStack channels work without a
-- pgr.subscribe entry. The proxy accepts any /ws/_channel_<name>
-- and treats it as a public broadcast/presence room (audience is NULL
-- because no subscription is registered).
--
-- For a PRIVATE channel, register one with `pgr.subscribe(name, query,
-- 'notify', '{"sub":"<uuid>"}'::jsonb)` from a SECURITY DEFINER helper
-- — same pattern as example 03.
