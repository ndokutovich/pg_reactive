#!/usr/bin/env node
// Version gate.
//
//   node scripts/versions/check.mjs            snapshot + feed, EOL is fatal
//   node scripts/versions/check.mjs --strict   also fail on stale patches
//   node scripts/versions/check.mjs --offline  snapshot only, no network
//   node scripts/versions/check.mjs --write    regenerate docs/VERSIONS.md
//
// Two independent checks:
//   1. Snapshot — the committed doc must match the pins in the tree. Fully
//      deterministic; safe to run on every push.
//   2. Freshness — every pin is compared with the endoflife.date feed for its
//      own cycle. EOL is always fatal (no patch is coming); being behind the
//      latest patch of a live branch is fatal only with --strict, because
//      upstream releases would otherwise redden unrelated PRs.
//
// States: ok | stale | eol | floating | unknown. `floating` means only a
// major/minor is pinned (docker tag `postgres:16-bookworm`), so "latest patch"
// cannot be asserted either way.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { collect, renderTable, ROOT } from "./inventory.mjs";
import { judge, validateRules } from "./judge.mjs";

const args = new Set(process.argv.slice(2));
const WRITE = args.has("--write");
const STRICT = args.has("--strict");
const OFFLINE = args.has("--offline");

const DOC = path.join(ROOT, "docs/VERSIONS.md");
const BEGIN = "<!-- versions:begin -->";
const END = "<!-- versions:end -->";
const RULES = JSON.parse(readFileSync(path.join(ROOT, "scripts/versions/rules.json"), "utf8"));

// A floor that is neither "eol" nor a version must never be read as "no floor":
// that is exactly how an EOL branch used to pass as green.
const ruleErrors = validateRules(RULES);
if (ruleErrors.length) {
  for (const e of ruleErrors) console.error(`FAIL  rules.json: ${e}`);
  process.exit(1);
}

const rows = collect();
const table = renderTable(rows);

// ── 1. Snapshot ──────────────────────────────────────────────────────────────

function readDoc() {
  if (!existsSync(DOC)) return null;
  const text = readFileSync(DOC, "utf8");
  const begin = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (begin === -1 || end === -1) return null;
  return { text, block: text.slice(begin + BEGIN.length, end).trim() };
}

function writeDoc() {
  const header = [
    "# Version inventory",
    "",
    "Generated by `node scripts/versions/check.mjs --write`. Every pin that decides",
    "what runs — Dockerfile bases, CI toolchains, compose images. Do not edit the",
    "table by hand: `check.mjs` fails when it drifts from the tree.",
    "",
    BEGIN,
    table,
    END,
    "",
    "## How freshness is judged",
    "",
    "The threshold is not stored here. `scripts/versions/check.mjs` compares each",
    "pin with the endoflife.date feed for its own cycle: a pin on an older patch",
    "of a live branch is `stale`, a dead branch is `eol`. `scripts/versions/rules.json`",
    "carries only what a CVE bulletin pins more precisely than \"latest\", plus",
    "branches declared dead by hand.",
    "",
    "EOL fails the scheduled check unconditionally. Stale fails it with `--strict`.",
    "A pin that names only a major/minor (a floating Docker tag) is reported as",
    "`floating` — the patch level is the registry's choice, not ours.",
    "",
  ].join("\n");
  writeFileSync(DOC, header, "utf8");
  console.log(`wrote ${path.relative(ROOT, DOC)} (${rows.length} pins)`);
}

const existing = readDoc();
if (WRITE) {
  writeDoc(existing);
} else if (!existing) {
  console.error(`FAIL  ${path.relative(ROOT, DOC)} is missing or has no ${BEGIN} block — run with --write`);
  process.exitCode = 1;
} else if (existing.block !== table.trim()) {
  console.error(`FAIL  ${path.relative(ROOT, DOC)} drifted from the tree — run: node scripts/versions/check.mjs --write`);
  const a = existing.block.split("\n");
  const b = table.trim().split("\n");
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) console.error(`  line ${i + 1}: committed "${a[i] ?? ""}" != tree "${b[i] ?? ""}"`);
  }
  process.exitCode = 1;
} else {
  console.log(`OK    snapshot matches the tree (${rows.length} pins)`);
}

if (WRITE || OFFLINE) {
  process.exit(process.exitCode ?? 0);
}

// ── 2. Freshness ─────────────────────────────────────────────────────────────

const products = [...new Set(rows.map((r) => r.feed))];
const feeds = new Map();
for (const product of products) {
  try {
    const res = await fetch(`https://endoflife.date/api/${product}.json`, {
      headers: { "user-agent": "pgstack-version-check" },
      signal: AbortSignal.timeout(20000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    feeds.set(product, await res.json());
  } catch (e) {
    feeds.set(product, null);
    console.error(`WARN  feed ${product} unavailable: ${e.message}`);
  }
}

const today = new Date().toISOString().slice(0, 10);

const judged = rows.map((r) => ({ ...r, ...judge(r, { feeds, rules: RULES, today }) }));

const icon = { ok: "ok  ", stale: "STALE", eol: "EOL ", floating: "float", unknown: "??  " };
const seenRuntime = new Set();
console.log("");
for (const r of judged) {
  // One line per runtime+source; the doc has the exhaustive list.
  const key = `${r.id}|${r.source}`;
  if (seenRuntime.has(key)) continue;
  seenRuntime.add(key);
  console.log(`  ${icon[r.state]}  ${r.id.padEnd(9)} ${String(r.version ?? "—").padEnd(10)} ${r.source}${r.note ? `  (${r.note})` : ""}`);
}

const eol = judged.filter((r) => r.state === "eol");
const stale = judged.filter((r) => r.state === "stale");
console.log("");

if (eol.length) {
  console.error(`FAIL  ${eol.length} pin(s) on a dead branch — no patch is coming`);
  process.exitCode = 1;
}
if (stale.length) {
  console.error(`${STRICT ? "FAIL" : "WARN"}  ${stale.length} pin(s) behind the latest patch of a live branch`);
  if (STRICT) process.exitCode = 1;
}
if (!eol.length && !stale.length) console.log("OK    every pin is on a live branch at its latest patch");
