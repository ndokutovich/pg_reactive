#!/usr/bin/env bash
#
# bootstrap-env.sh — generate .env for a production pgStack deploy.
#
# Idempotent: on the first run it creates .env with cryptographically
# random values for every required secret. On every subsequent run it
# ONLY fills in keys that are still missing (so existing live secrets
# are never rotated out from under running services). Existing values
# are never overwritten.
#
# Usage:
#   bash scripts/bootstrap-env.sh                 # writes ./.env
#   ENV_FILE=/custom/.env bash scripts/...        # writes elsewhere
#   SITE_URL=https://app.example.com bash ...     # override one value
#
# Designed for the deploy workflow:
#
#   cd /opt/apps/pg-reactive-src
#   bash scripts/bootstrap-env.sh
#   docker compose -f examples/docker-compose.yml \
#                  -f examples/docker-compose.prod.yml up -d
#
# After first run, rotate a secret manually by editing .env and
# `docker compose up -d` again — this script will not touch already-set
# values.

set -euo pipefail

ENV_FILE="${ENV_FILE:-.env}"

# Random 32-character URL-safe secret — suitable for JWT_SECRET,
# ANON_KEY, SERVICE_ROLE_KEY, POSTGRES_PASSWORD, SECRETS_ENCRYPTION_KEY.
#
# Why alphanumeric instead of straight base64: POSTGRES_PASSWORD lands
# verbatim inside a `postgres://postgres:${...}@db:5432/...` connection
# string. base64's `+`, `/`, `=` are valid base64 alphabet but break
# URL parsing in subtle ways — pgx's parseSettings rejected a generated
# password and the proxy crash-looped on startup. ~190 bits of entropy
# from 32 alphanumeric characters keeps every secret comfortably above
# its 32+ byte minimum without ever needing URL-encoding.
rand_b64() {
  LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32
}

# SECRETS_ENCRYPTION_KEY is special: the proxy parses it as base64-encoded
# 32 raw bytes (AES-256 key, secrets.DecodeKey in proxy-go/secrets/
# secretbox.go). 32 alphanumeric chars decodes to 24 bytes and fails the
# length check — so we need actual base64-of-32-bytes here (44 chars
# including padding). Lives in an env file only, never in a URL, so the
# +/= alphabet is fine.
rand_aes32_b64() {
  openssl rand -base64 32 | tr -d '\n'
}

# Load existing values so we know which keys to leave alone.
# Empty placeholder values (`KEY=` with no value) are treated as MISSING,
# not as "already configured" — otherwise a half-filled template (the
# pattern shipped in deploy/templates/*/.env.example) would silently
# poison the deploy with empty mandatory secrets, and compose would then
# fail with "required variable POSTGRES_PASSWORD is missing".
declare -A existing
if [ -f "$ENV_FILE" ]; then
  while IFS='=' read -r k v; do
    [[ "$k" =~ ^[A-Z_][A-Z0-9_]*$ ]] || continue
    [ -n "$v" ] || continue
    existing["$k"]=1
  done < <(grep -E '^[A-Z_][A-Z0-9_]*=' "$ENV_FILE" || true)
fi

# Each entry: KEY=value-generator OR KEY=literal-default.
# If KEY is already present in $ENV_FILE we skip it.
declare -a additions=()
add() {
  local key="$1" value="$2"
  if [ -n "${existing[$key]:-}" ]; then
    return
  fi
  # Quote the value so any base64 = padding survives docker-compose parsing.
  additions+=("${key}=${value}")
}

# Allow callers to override individual values via the environment.
v_or_rand()       { local k="$1"; printf '%s' "${!k:-$(rand_b64)}"; }
v_or_rand_aes32() { local k="$1"; printf '%s' "${!k:-$(rand_aes32_b64)}"; }
v_or_lit()        { local k="$1" def="$2"; printf '%s' "${!k:-$def}"; }

add POSTGRES_PASSWORD       "$(v_or_rand       POSTGRES_PASSWORD)"
# Login password for the powerless `authenticator` role the proxy connects as
# (gemini audit P2). URL-safe (same generator as POSTGRES_PASSWORD) because it
# lands in the proxy's DATABASE_URL. The db image's 20-authenticator-login.sh
# applies it; both the db and proxy services read this one value.
add AUTHENTICATOR_PASSWORD  "$(v_or_rand       AUTHENTICATOR_PASSWORD)"
add JWT_SECRET              "$(v_or_rand       JWT_SECRET)"
add ANON_KEY                "$(v_or_rand       ANON_KEY)"
add SERVICE_ROLE_KEY        "$(v_or_rand       SERVICE_ROLE_KEY)"
add SECRETS_ENCRYPTION_KEY  "$(v_or_rand_aes32 SECRETS_ENCRYPTION_KEY)"
add SITE_URL                "$(v_or_lit  SITE_URL    'http://localhost')"
add ALLOWED_ORIGINS         "$(v_or_lit  ALLOWED_ORIGINS '')"

if [ "${#additions[@]}" -eq 0 ]; then
  echo "bootstrap-env.sh: $ENV_FILE already has every required key — nothing to do."
  exit 0
fi

# Atomic append: write to a temp file, then move into place.
# Strip lines whose value is empty (e.g. `POSTGRES_PASSWORD=` placeholders
# from .env.example) so the appended populated values aren't shadowed by
# stale empty entries. Comments and non-secret lines pass through.
tmp="${ENV_FILE}.tmp.$$"
{
  if [ -f "$ENV_FILE" ]; then
    sed -E '/^[A-Z_][A-Z0-9_]*=$/d' "$ENV_FILE"
    # Make sure there is a trailing newline before we append.
    [ -z "$(tail -c1 "$ENV_FILE")" ] || printf '\n'
  else
    printf '# Generated by scripts/bootstrap-env.sh on %s — secrets only.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '# Edit by hand to rotate; re-running this script never overwrites existing values.\n\n'
  fi
  printf '%s\n' "${additions[@]}"
} > "$tmp"

# Move into place + tight permissions before announcing.
mv "$tmp" "$ENV_FILE"
chmod 600 "$ENV_FILE" 2>/dev/null || true

# Report what we added — values redacted to keep them out of CI logs.
echo "bootstrap-env.sh: wrote $ENV_FILE (mode 600). New keys:"
for entry in "${additions[@]}"; do
  printf '  %s=********\n' "${entry%%=*}"
done
